#!/usr/bin/env python3
import argparse
import concurrent.futures
import json
import os
import re
import signal
import socket
import statistics
import subprocess
import sys
import time
from datetime import datetime
from pathlib import Path

import requests


HOST = "127.0.0.1"
TP = 2
DP = 1
DATA_TYPE = "bfloat16"
MAX_NEW_TOKENS = 128
MAX_REQ_TOTAL_LEN = 2048
MAX_TOTAL_TOKEN_NUM = 131072
BATCH_MAX_TOKENS = 65536
STARTUP_TIMEOUT_S = 900
REQUEST_TIMEOUT_S = 1500
RUN_BATCH_TIMEOUT_MS = 0
CONSTRAINT_MODES = ("xgrammar", "pre3")
JSONSCHEMABENCH_UNIQUE_ID = "o9703"
JSONSCHEMABENCH_SCHEMA = r"""{
    "$schema": "http://json-schema.org/draft-04/schema#",
    "type": "object",
    "properties": {
        "kind": {
            "type": "string",
            "default": "req",
            "readonly": "true",
            "description": "Defines that the message is a request"
        },
        "id": {
            "type": "string",
            "description": "Request ID generated by the client. It should be unique per WebSocket session in order to identify the request. This ID will be reflected by the server in the response to the request.",
            "minLength": 1,
            "maxLength": 64,
            "default": "0"
        },
        "type": {
            "description": "Contains one of the APIs request type names",
            "type": "string"
        }
    },
    "required": [
        "id",
        "type"
    ]
}"""
JSON_GRAMMAR_EBNF = r"""
root ::= basic_array | basic_object
basic_any ::= basic_number | basic_string | basic_boolean | basic_null | basic_array | basic_object
basic_integer ::= ("0" | "-"? [1-9] [0-9]*) ".0"?
basic_number ::= ("0" | "-"? [1-9] [0-9]*) ("." [0-9]+)? ([eE] [+-]? [0-9]+)?
basic_string ::= (([\"] basic_string_1 [\"]))
basic_string_1 ::= "" | [^"\\\x00-\x1F] basic_string_1 | "\\" escape basic_string_1
escape ::= ["\\/bfnrt] | "u" [A-Fa-f0-9] [A-Fa-f0-9] [A-Fa-f0-9] [A-Fa-f0-9]
basic_boolean ::= "true" | "false"
basic_null ::= "null"
basic_array ::= "[" ("" | ws basic_any (ws "," ws basic_any)*) ws "]"
basic_object ::= "{" ("" | ws basic_string ws ":" ws basic_any ( ws "," ws basic_string ws ":" ws basic_any)*) ws "}"
ws ::= [ \n\t]*
"""
MEAN_PER_TOKEN_RE = re.compile(r"mean_per_token_cost_time:\s*([0-9.eE+-]+)ms")
PROXY_ENV_KEYS = (
    "HTTP_PROXY",
    "HTTPS_PROXY",
    "ALL_PROXY",
    "http_proxy",
    "https_proxy",
    "all_proxy",
)


def parse_args():
    parser = argparse.ArgumentParser(
        description=(
            "Benchmark xgrammar vs pre3 on one fixed JSONSchemaBench prompt with the "
            "JSON EBNF grammar from test/format_out/test_xgrammar_constraint.py."
        )
    )
    parser.add_argument("--batch_size", type=int, required=True)
    parser.add_argument("--model_dir", required=True)
    return parser.parse_args()


def disable_local_proxies(env: dict):
    for proxy_key in PROXY_ENV_KEYS:
        env.pop(proxy_key, None)
    env["NO_PROXY"] = "127.0.0.1,localhost"
    env["no_proxy"] = "127.0.0.1,localhost"


def is_port_free(port: int):
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.settimeout(0.2)
        return sock.connect_ex((HOST, port)) != 0


def find_free_port():
    for _ in range(100):
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
            sock.bind((HOST, 0))
            port = sock.getsockname()[1]
        if is_port_free(port):
            return port
    raise RuntimeError("failed to find a free port")


def auto_select_gpus(count: int):
    try:
        output = subprocess.check_output(
            [
                "nvidia-smi",
                "--query-gpu=index,memory.used,utilization.gpu",
                "--format=csv,noheader,nounits",
            ],
            text=True,
            timeout=10,
        )
    except Exception:
        return None

    gpus = []
    for line in output.splitlines():
        parts = [part.strip() for part in line.split(",")]
        if len(parts) != 3:
            continue
        try:
            index, memory_used, gpu_util = int(parts[0]), int(parts[1]), int(parts[2])
        except ValueError:
            continue
        gpus.append((memory_used, gpu_util, index))
    if len(gpus) < count:
        return None
    gpus.sort()
    return ",".join(str(index) for _, _, index in gpus[:count])


def tail_file(path: Path, max_lines: int = 80):
    if not path.exists():
        return ""
    return "\n".join(path.read_text(errors="replace").splitlines()[-max_lines:])


def wait_readiness(url: str, proc: subprocess.Popen, stdout_path: Path):
    deadline = time.time() + STARTUP_TIMEOUT_S
    session = requests.Session()
    session.trust_env = False
    while time.time() < deadline:
        if proc.poll() is not None:
            raise RuntimeError(
                f"server exited with code {proc.returncode}\nlast server output:\n{tail_file(stdout_path)}"
            )
        try:
            resp = session.get(url, timeout=5)
            if resp.status_code == 200:
                return
        except requests.RequestException:
            pass
        time.sleep(2)
    raise TimeoutError(f"server did not become ready within {STARTUP_TIMEOUT_S}s")


def stop_process(proc: subprocess.Popen):
    if proc.poll() is not None:
        return
    try:
        os.killpg(proc.pid, signal.SIGTERM)
    except ProcessLookupError:
        return
    try:
        proc.wait(timeout=60)
    except subprocess.TimeoutExpired:
        os.killpg(proc.pid, signal.SIGKILL)
        proc.wait(timeout=30)


def build_server_cmd(model_dir: str, mode: str, port: int, batch_size: int):
    return [
        sys.executable,
        "-m",
        "lightllm.server.api_server",
        "--model_dir",
        model_dir,
        "--host",
        HOST,
        "--port",
        str(port),
        "--output_constraint_mode",
        mode,
        "--running_max_req_size",
        str(batch_size),
        "--graph_max_batch_size",
        str(batch_size),
        "--max_req_total_len",
        str(MAX_REQ_TOTAL_LEN),
        "--max_total_token_num",
        str(MAX_TOTAL_TOKEN_NUM),
        "--batch_max_tokens",
        str(BATCH_MAX_TOKENS),
        "--tp",
        str(TP),
        "--dp",
        str(DP),
        "--data_type",
        DATA_TYPE,
        "--trust_remote_code",
        # "--disable_cudagraph",
    ]


def start_server(model_dir: str, mode: str, port: int, batch_size: int, run_dir: Path, cuda_visible_devices: str):
    repo_root = Path(__file__).resolve().parents[1]
    log_dir = run_dir / "lightllm_logs"
    log_dir.mkdir(parents=True, exist_ok=True)
    stdout_path = run_dir / "server_stdout.log"

    env = os.environ.copy()
    disable_local_proxies(env)
    env["LIGHTLLM_RUN_BATCH"] = str(batch_size)
    env["LIGHTLLM_RUN_BATCH_TIMEOUT_MS"] = str(RUN_BATCH_TIMEOUT_MS)
    env["DISABLE_CHECK_MAX_LEN_INFER"] = "1"
    env["LIGHTLLM_LOG_DIR"] = str(log_dir)
    env.setdefault("LIGHTLLM_LOG_LEVEL", "info")
    env["PYTHONPATH"] = os.pathsep.join(
        [str(repo_root / "kernel"), str(repo_root), env.get("PYTHONPATH", "")]
    )
    env["PATH"] = os.pathsep.join([str(Path(sys.executable).resolve().parent), env.get("PATH", "")])
    if cuda_visible_devices:
        env["CUDA_VISIBLE_DEVICES"] = cuda_visible_devices

    stdout = stdout_path.open("w")
    proc = subprocess.Popen(
        build_server_cmd(model_dir, mode, port, batch_size),
        cwd=repo_root,
        env=env,
        stdout=stdout,
        stderr=subprocess.STDOUT,
        start_new_session=True,
        text=True,
    )
    try:
        wait_readiness(f"http://{HOST}:{port}/readiness", proc, stdout_path)
    except Exception:
        stop_process(proc)
        stdout.close()
        raise
    stdout.close()
    return proc, log_dir, stdout_path


def make_payload():
    prompt = (
        "Generate one valid JSON object that satisfies this JSONSchemaBench schema.\n"
        f"Schema id: {JSONSCHEMABENCH_UNIQUE_ID}\n"
        f"JSON schema:\n{JSONSCHEMABENCH_SCHEMA}\n"
        "Return JSON only."
    )
    return {
        "inputs": prompt,
        "parameters": {
            "do_sample": False,
            "ignore_eos": False,
            "max_new_tokens": MAX_NEW_TOKENS,
            "guided_grammar": JSON_GRAMMAR_EBNF,
        },
    }


def post_one(url: str, payload: dict):
    start = time.time()
    session = requests.Session()
    session.trust_env = False
    resp = session.post(url, json=payload, timeout=REQUEST_TIMEOUT_S)
    latency = time.time() - start
    if resp.status_code != 200:
        raise RuntimeError(f"status={resp.status_code} body={resp.text[:500]}")
    data = resp.json()
    return {
        "latency_s": latency,
        "count_output_tokens": data.get("count_output_tokens", 0),
        "finish_reason": data.get("finish_reason", ""),
    }


def send_requests(port: int, batch_size: int):
    url = f"http://{HOST}:{port}/generate"
    payload = make_payload()
    results = []
    errors = []
    executor = concurrent.futures.ThreadPoolExecutor(max_workers=batch_size)
    futures = [executor.submit(post_one, url, payload) for _ in range(batch_size)]
    try:
        for future in concurrent.futures.as_completed(futures, timeout=REQUEST_TIMEOUT_S + 30):
            try:
                results.append(future.result())
            except Exception as exc:
                errors.append(str(exc))
    except concurrent.futures.TimeoutError:
        errors.append(f"only {len(results)}/{len(futures)} requests finished before timeout")
    finally:
        for future in futures:
            future.cancel()
        executor.shutdown(wait=False, cancel_futures=True)
    return results, "; ".join(errors[:3]) if errors else None


def parse_mean_per_token(stdout_path: Path, log_dir: Path):
    values = []
    if stdout_path.exists():
        values = [float(match.group(1)) for match in MEAN_PER_TOKEN_RE.finditer(stdout_path.read_text(errors="replace"))]
        if values:
            return {"source": "server_stdout", "mean_per_token_ms": statistics.mean(values), "sample_count": len(values)}

    for path in log_dir.glob("*.log"):
        text = path.read_text(errors="replace")
        values.extend(float(match.group(1)) for match in MEAN_PER_TOKEN_RE.finditer(text))
    return {
        "source": "lightllm_logs" if values else "missing",
        "mean_per_token_ms": statistics.mean(values) if values else None,
        "sample_count": len(values),
    }


def run_mode(model_dir: str, mode: str, batch_size: int, output_dir: Path, cuda_visible_devices: str):
    port = find_free_port()
    run_dir = output_dir / mode
    run_dir.mkdir(parents=True, exist_ok=True)
    proc = None
    client_results = []
    request_error = None
    try:
        print(f"Running {mode} on port {port} ...", flush=True)
        proc, log_dir, stdout_path = start_server(model_dir, mode, port, batch_size, run_dir, cuda_visible_devices)
        client_results, request_error = send_requests(port, batch_size)
        time.sleep(3)
    finally:
        if proc is not None:
            stop_process(proc)

    parsed = parse_mean_per_token(stdout_path, log_dir)
    parsed.update(
        {
            "mode": mode,
            "port": port,
            "ok_requests": len(client_results),
            "avg_client_latency_s": (
                statistics.mean([r["latency_s"] for r in client_results]) if client_results else None
            ),
            "avg_output_tokens": (
                statistics.mean([r["count_output_tokens"] for r in client_results]) if client_results else None
            ),
            "request_error": request_error,
            "log_dir": str(log_dir),
            "server_stdout": str(stdout_path),
        }
    )
    return parsed


def fmt_ms(value):
    return "missing" if value is None else f"{value:.4f} ms/token"


def main():
    args = parse_args()
    if args.batch_size <= 0:
        raise ValueError("--batch_size must be positive")

    cuda_visible_devices = auto_select_gpus(TP)
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    output_dir = Path(f"experiment_results/jsonschemabench_ebnf_batch{args.batch_size}_{stamp}")
    output_dir.mkdir(parents=True, exist_ok=True)

    summary = {
        "model_dir": args.model_dir,
        "batch_size": args.batch_size,
        "requests": args.batch_size,
        "cuda_visible_devices": cuda_visible_devices,
        "test_case": {
            "dataset": "epfl-dlab/JSONSchemaBench",
            "config": "Github_easy",
            "split": "test",
            "unique_id": JSONSCHEMABENCH_UNIQUE_ID,
            "schema_chars": len(JSONSCHEMABENCH_SCHEMA),
            "request_policy": "repeat the same prompt batch_size times",
        },
        "constraint": "guided_grammar using JSON EBNF from test/format_out/test_xgrammar_constraint.py",
        "fixed_server_settings": {
            "tp": TP,
            "dp": DP,
            "data_type": DATA_TYPE,
            "max_new_tokens": MAX_NEW_TOKENS,
            "max_req_total_len": MAX_REQ_TOTAL_LEN,
            "max_total_token_num": MAX_TOTAL_TOKEN_NUM,
            "batch_max_tokens": BATCH_MAX_TOKENS,
            "LIGHTLLM_RUN_BATCH_TIMEOUT_MS": RUN_BATCH_TIMEOUT_MS,
            "DISABLE_CHECK_MAX_LEN_INFER": "1",
            "disable_cudagraph": True,
        },
        "modes": {},
    }

    for mode in CONSTRAINT_MODES:
        summary["modes"][mode] = run_mode(args.model_dir, mode, args.batch_size, output_dir, cuda_visible_devices)

    xgrammar_ms = summary["modes"]["xgrammar"]["mean_per_token_ms"]
    pre3_ms = summary["modes"]["pre3"]["mean_per_token_ms"]
    reduction_pct = None
    if xgrammar_ms is not None and pre3_ms is not None and xgrammar_ms != 0:
        reduction_pct = (xgrammar_ms - pre3_ms) / xgrammar_ms * 100.0
    summary["pre3_latency_reduction_pct"] = reduction_pct

    summary_path = output_dir / "summary.json"
    summary_path.write_text(json.dumps(summary, indent=2, ensure_ascii=False))

    print("\nBenchmark result")
    print(f"xgrammar mean per token latency: {fmt_ms(xgrammar_ms)}")
    print(f"pre3 mean per token latency: {fmt_ms(pre3_ms)}")
    if reduction_pct is None:
        print("pre3 latency reduction vs xgrammar: missing")
    else:
        print(f"pre3 latency reduction vs xgrammar: {reduction_pct:.2f}%")
    print(f"xgrammar log dir: {summary['modes']['xgrammar']['log_dir']}")
    print(f"xgrammar stdout log: {summary['modes']['xgrammar']['server_stdout']}")
    print(f"pre3 log dir: {summary['modes']['pre3']['log_dir']}")
    print(f"pre3 stdout log: {summary['modes']['pre3']['server_stdout']}")
    print(f"summary: {summary_path}")


if __name__ == "__main__":
    main()
